/// Plain-text monthly sterilisation register. A text file is shared (or
/// printed from the share sheet) so the log works without the PDF stack.
library;

import 'package:ampdent_core/ampdent_core.dart';
import 'package:ampdent_mobile/core/formatting.dart';

import 'compliance_labels.dart';

/// Month names for titles and file names.
const List<String> monthNames = [
  'January',
  'February',
  'March',
  'April',
  'May',
  'June',
  'July',
  'August',
  'September',
  'October',
  'November',
  'December',
];

/// `sterilisation-log-2026-10.txt`.
String sterilisationLogFileName(int year, int month) =>
    'sterilisation-log-$year-${month.toString().padLeft(2, '0')}.txt';

String _pad(String value, int width) =>
    value.length >= width ? value.substring(0, width) : value.padRight(width);

String _num(num? value, {String unit = ''}) =>
    value == null ? '-' : '$value$unit';

/// Renders the register for one month as fixed-width text, oldest cycle
/// first. [operatorNames] maps member ids to display names.
String sterilisationLogText({
  required Clinic clinic,
  required int year,
  required int month,
  required List<SterilisationCycle> cycles,
  Map<String, String> operatorNames = const {},
  DateTime? generatedAt,
}) {
  final b = StringBuffer();
  b.writeln('STERILISATION REGISTER - ${monthNames[month - 1]} $year');
  b.writeln(clinic.name);
  final address = [
    ...clinic.addressLines,
    clinic.city,
    clinic.pincode,
  ].where((s) => s.trim().isNotEmpty).join(', ');
  if (address.isNotEmpty) b.writeln(address);
  b.writeln('Ph: ${clinic.phone}');
  b.writeln();
  final header =
      '${_pad('No.', 9)}${_pad('Date & time', 19)}${_pad('Autoclave', 14)}'
      '${_pad('Type', 9)}${_pad('Temp', 7)}${_pad('kPa', 6)}${_pad('Hold', 6)}'
      '${_pad('CI', 5)}${_pad('BI', 9)}Operator';
  b.writeln(header);
  b.writeln(''.padRight(header.length + 12, '-'));
  if (cycles.isEmpty) {
    b.writeln('No cycles recorded this month.');
  }
  for (final c in cycles) {
    b.writeln(
      '${_pad(c.cycleNumber, 9)}'
      '${_pad(AppFormat.dateTime(c.cycledAt), 19)}'
      '${_pad(c.autoclaveName, 14)}'
      '${_pad(cycleTypeLabel(c.cycleType), 9)}'
      '${_pad(_num(c.temperatureC, unit: 'C'), 7)}'
      '${_pad(_num(c.pressureKpa), 6)}'
      '${_pad(_num(c.durationMinutes, unit: 'm'), 6)}'
      '${_pad(c.chemicalIndicatorPassed ? 'Pass' : 'FAIL', 5)}'
      '${_pad(biologicalResultLabel(c.biologicalIndicatorResult), 9)}'
      '${operatorNames[c.operatorId] ?? c.operatorId}',
    );
    final extras = [
      if (c.loadContents != null && c.loadContents!.isNotEmpty)
        'Load: ${c.loadContents}',
      if (c.note != null && c.note!.isNotEmpty) 'Note: ${c.note}',
    ];
    for (final e in extras) {
      b.writeln('         $e');
    }
  }
  b.writeln();
  final sporeTests = cycles
      .where(
        (c) =>
            c.biologicalIndicatorResult != null &&
            c.biologicalIndicatorResult != BiologicalIndicatorResult.notDone,
      )
      .length;
  final failures = cycles.where((c) => !c.passed).length;
  b.writeln('Cycles: ${cycles.length}   Spore tests: $sporeTests   ');
  b.writeln('Failed cycles: $failures');
  b.writeln();
  b.writeln('Signed: ______________________   Date: ____________');
  b.writeln(
    'Generated by AmpDent on '
    '${AppFormat.dateTime(generatedAt ?? DateTime.now())}',
  );
  return b.toString();
}
